CREATE TABLE authors (
  author_id INT PRIMARY KEY,
  name VARCHAR(40) COLLATE NOCASE,
  country VARCHAR(30) COLLATE NOCASE
);
CREATE TABLE books (
  book_id INT PRIMARY KEY,
  title VARCHAR(60) COLLATE NOCASE,
  author_id INT,
  category VARCHAR(20) COLLATE NOCASE,
  price DECIMAL(7,2),
  published_year INT
);
CREATE TABLE members (
  member_id INT PRIMARY KEY,
  name VARCHAR(40) COLLATE NOCASE,
  city VARCHAR(30) COLLATE NOCASE,
  joined_date DATE
);
CREATE TABLE loans (
  loan_id INT PRIMARY KEY,
  member_id INT,
  book_id INT,
  loan_date DATE,
  return_date DATE
);

