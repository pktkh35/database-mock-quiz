CREATE TABLE regions (
  region_id INT PRIMARY KEY,
  region_name VARCHAR(25) COLLATE NOCASE
);
CREATE TABLE countries (
  country_id CHAR(2) PRIMARY KEY COLLATE NOCASE,
  country_name VARCHAR(40) COLLATE NOCASE,
  region_id INT
);
CREATE TABLE locations (
  location_id INT PRIMARY KEY,
  street_address VARCHAR(40) COLLATE NOCASE,
  postal_code VARCHAR(12),
  city VARCHAR(30) COLLATE NOCASE,
  state_province VARCHAR(25) COLLATE NOCASE,
  country_id CHAR(2) COLLATE NOCASE
);
CREATE TABLE departments (
  department_id INT PRIMARY KEY,
  department_name VARCHAR(30) COLLATE NOCASE,
  manager_id INT,
  location_id INT
);
CREATE TABLE jobs (
  job_id VARCHAR(10) PRIMARY KEY COLLATE NOCASE,
  job_title VARCHAR(35) COLLATE NOCASE,
  min_salary DECIMAL(6,0),
  max_salary DECIMAL(6,0)
);
CREATE TABLE employees (
  employee_id INT PRIMARY KEY,
  first_name VARCHAR(20) COLLATE NOCASE,
  last_name VARCHAR(25) COLLATE NOCASE,
  email VARCHAR(25) COLLATE NOCASE,
  phone_number VARCHAR(20),
  hire_date DATE,
  job_id VARCHAR(10) COLLATE NOCASE,
  salary DECIMAL(8,2),
  commission_pct DECIMAL(2,2),
  manager_id INT,
  department_id INT
);
CREATE TABLE job_history (
  employee_id INT,
  start_date DATE,
  end_date DATE,
  job_id VARCHAR(10) COLLATE NOCASE,
  department_id INT
);

