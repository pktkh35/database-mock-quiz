CREATE TABLE offices (
  officeCode VARCHAR(10) PRIMARY KEY,
  city VARCHAR(50) COLLATE NOCASE,
  phone VARCHAR(50),
  addressLine1 VARCHAR(50) COLLATE NOCASE,
  addressLine2 VARCHAR(50) COLLATE NOCASE,
  state VARCHAR(50) COLLATE NOCASE,
  country VARCHAR(50) COLLATE NOCASE,
  postalCode VARCHAR(15),
  territory VARCHAR(10) COLLATE NOCASE
);
CREATE TABLE employees (
  employeeNumber INT PRIMARY KEY,
  lastName VARCHAR(50) COLLATE NOCASE,
  firstName VARCHAR(50) COLLATE NOCASE,
  extension VARCHAR(10),
  email VARCHAR(100) COLLATE NOCASE,
  officeCode VARCHAR(10),
  reportsTo INT,
  jobTitle VARCHAR(50) COLLATE NOCASE
);
CREATE TABLE customers (
  customerNumber INT PRIMARY KEY,
  customerName VARCHAR(50) COLLATE NOCASE,
  contactLastName VARCHAR(50) COLLATE NOCASE,
  contactFirstName VARCHAR(50) COLLATE NOCASE,
  phone VARCHAR(50),
  addressLine1 VARCHAR(50) COLLATE NOCASE,
  addressLine2 VARCHAR(50) COLLATE NOCASE,
  city VARCHAR(50) COLLATE NOCASE,
  state VARCHAR(50) COLLATE NOCASE,
  postalCode VARCHAR(15),
  country VARCHAR(50) COLLATE NOCASE,
  salesRepEmployeeNumber INT,
  creditLimit DECIMAL(10,2)
);
CREATE TABLE productlines (
  productLine VARCHAR(50) PRIMARY KEY COLLATE NOCASE,
  textDescription VARCHAR(4000) COLLATE NOCASE
);
CREATE TABLE products (
  productCode VARCHAR(15) PRIMARY KEY COLLATE NOCASE,
  productName VARCHAR(70) COLLATE NOCASE,
  productLine VARCHAR(50) COLLATE NOCASE,
  productScale VARCHAR(10),
  productVendor VARCHAR(50) COLLATE NOCASE,
  quantityInStock INT,
  buyPrice DECIMAL(10,2),
  MSRP DECIMAL(10,2)
);
CREATE TABLE orders (
  orderNumber INT PRIMARY KEY,
  orderDate DATE,
  requiredDate DATE,
  shippedDate DATE,
  status VARCHAR(15) COLLATE NOCASE,
  comments VARCHAR(500) COLLATE NOCASE,
  customerNumber INT
);
CREATE TABLE orderdetails (
  orderNumber INT,
  productCode VARCHAR(15) COLLATE NOCASE,
  quantityOrdered INT,
  priceEach DECIMAL(10,2),
  orderLineNumber INT,
  PRIMARY KEY (orderNumber, productCode)
);
CREATE TABLE payments (
  customerNumber INT,
  checkNumber VARCHAR(50) COLLATE NOCASE,
  paymentDate DATE,
  amount DECIMAL(10,2),
  PRIMARY KEY (customerNumber, checkNumber)
);

